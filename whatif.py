"""
AcademiQ - What-If Academic Performance Scenario Analysis Utility
==================================================================
This standalone command-line tool allows students, educators, and counselors
to explore how hypothetical adjustments to individual student factors
(such as Attendance or Hours_Studied) shift the predicted Exam_Score
generated by the trained Multiple Linear Regression (MLR) pipeline.

Key Methodological Principles:
1. Controlled Comparison: Exactly one feature is varied at a time; all other
   18 features remain strictly constant.
2. Domain-Grounded Bounds: All scenario inputs are strictly validated against
   the observed ranges and categories from the Kaggle benchmark dataset.
3. Non-Causal Perspective: Predicted differences reflect empirical statistical
   associations within observational data, NOT guaranteed real-world improvements.
"""

import sys
import warnings
from pathlib import Path

# Suppress unpickling warnings for clean terminal presentation
warnings.filterwarnings("ignore")

import joblib
import pandas as pd

# Import reusable configuration and prompts from predict.py
from predict import (
    MODEL_PATH,
    FEATURE_COLUMNS,
    CATEGORICAL_OPTIONS,
    load_trained_pipeline,
    collect_student_features,
    prompt_numerical,
    prompt_categorical,
    get_performance_tier,
)

# -----------------------------------------------------------------------------
# Observed Dataset Ranges for Scenario Validation (Kaggle Training Set)
# -----------------------------------------------------------------------------
OBSERVED_NUMERICAL_BOUNDS = {
    "Hours_Studied": {"min": 1, "max": 43, "type": float, "desc": "Hours studied per week (Dataset range: 1 to 43)"},
    "Attendance": {"min": 60, "max": 100, "type": float, "desc": "Class attendance percentage (Dataset range: 60 to 100%)"},
    "Previous_Scores": {"min": 50, "max": 100, "type": float, "desc": "Previous exam score (Dataset range: 50 to 100)"},
    "Tutoring_Sessions": {"min": 0, "max": 8, "type": int, "desc": "Tutoring sessions per month (Dataset range: 0 to 8)"},
    "Sleep_Hours": {"min": 4, "max": 10, "type": float, "desc": "Sleep hours per night (Dataset range: 4 to 10)"},
    "Physical_Activity": {"min": 0, "max": 6, "type": float, "desc": "Physical activity hours/week (Dataset range: 0 to 6)"},
}

# Default sample baseline profile (typical median student)
